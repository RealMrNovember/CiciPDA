using System.Security.Cryptography;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace CiciPDA;

public sealed class CompanionMetadata
{
    [JsonPropertyName("package")] public string Package { get; set; } = "";
    [JsonPropertyName("versionName")] public string VersionName { get; set; } = "";
    [JsonPropertyName("versionCode")] public int VersionCode { get; set; }
    [JsonPropertyName("protocol")] public int Protocol { get; set; }
    [JsonPropertyName("minSdk")] public int MinSdk { get; set; }
    [JsonPropertyName("apk")] public string Apk { get; set; } = "";
    [JsonPropertyName("sha256")] public string Sha256 { get; set; } = "";
    [JsonPropertyName("signerCertSha256")] public string SignerCertSha256 { get; set; } = "";
}

/// <summary>A companion APK that passed every trust check and is safe to hand to `adb install`.</summary>
public sealed record VerifiedCompanion(CompanionMetadata Meta, string ApkPath, string Source);

public sealed class TrustException : Exception { public TrustException(string m) : base(m) { } }

/// <summary>
/// Trust chain for the Android companion:
///   1. companion.json must carry a valid ECDSA P-256 signature from the pinned release key (offline key, never the download host);
///   2. the APK's SHA-256 must equal the signed metadata;
///   3. the APK's signing certificate must equal both the signed metadata and the certificate pinned inside this application;
///   4. Android then verifies the APK signature itself at install time and refuses updates signed by a different key.
/// A hash from the same unverified server is therefore never enough.
/// </summary>
public static class ReleaseTrust
{
    public const string PackageName = "app.cicibyte.cicipda";

    /// <summary>Pinned release verification key (SubjectPublicKeyInfo, base64) and pinned APK signer certificate SHA-256 values.
    /// The values below belong to the DEVELOPMENT keys generated by tools/ReleaseSigner; replace them with production keys before shipping.</summary>
    public static string PinnedMetadataKey { get; set; } = Pins.MetadataKey;
    public static IReadOnlyCollection<string> PinnedSignerCerts { get; set; } = Pins.SignerCerts;
    public static bool IsDevelopmentTrust => Pins.IsDevelopment;

    public static VerifiedCompanion Verify(string metadataPath, string signaturePath, string apkDir, string source)
    {
        byte[] json = File.ReadAllBytes(metadataPath), sig = File.ReadAllBytes(signaturePath);
        VerifyMetadataSignature(json, sig);
        var meta = ParseMetadata(json);
        if (meta.Package != PackageName) throw new TrustException("Release metadata is for a different package.");
        if (meta.VersionCode <= 0 || string.IsNullOrWhiteSpace(meta.VersionName)) throw new TrustException("Release metadata has no version.");
        if (meta.Apk != Path.GetFileName(meta.Apk)) throw new TrustException("Release metadata names an unsafe file path.");
        var apk = Path.Combine(apkDir, meta.Apk);
        if (!File.Exists(apk)) throw new TrustException("The companion APK file is missing.");

        var actual = Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(apk))).ToLowerInvariant();
        if (!CryptographicOperations.FixedTimeEquals(System.Text.Encoding.ASCII.GetBytes(actual), System.Text.Encoding.ASCII.GetBytes(meta.Sha256.ToLowerInvariant())))
            throw new TrustException("The companion APK does not match the signed release metadata (hash mismatch).");

        IReadOnlyList<string> certs;
        try { certs = ApkSigning.SignerCertSha256(apk); }
        catch (InvalidDataException ex) { throw new TrustException("The companion APK signature block is unreadable: " + ex.Message); }
        var expected = meta.SignerCertSha256.ToLowerInvariant();
        if (!certs.Contains(expected)) throw new TrustException("The companion APK is signed by a different certificate than the release metadata states.");
        if (!PinnedSignerCerts.Contains(expected)) throw new TrustException("The companion APK signer is not trusted by this version of CiciPDA.");
        return new VerifiedCompanion(meta, apk, source);
    }

    /// <summary>Parses metadata that has already passed signature verification (tolerates a UTF-8 BOM).</summary>
    public static CompanionMetadata ParseMetadata(byte[] json)
    {
        var span = json.AsSpan();
        if (span.Length >= 3 && span[0] == 0xEF && span[1] == 0xBB && span[2] == 0xBF) span = span[3..];
        try { return JsonSerializer.Deserialize<CompanionMetadata>(span) ?? throw new TrustException("Release metadata is empty."); }
        catch (JsonException ex) { throw new TrustException("Release metadata is not valid JSON: " + ex.Message); }
    }

    public static void VerifyMetadataSignature(byte[] json, byte[] signature)
    {
        using var ecdsa = ECDsa.Create();
        ecdsa.ImportSubjectPublicKeyInfo(Convert.FromBase64String(PinnedMetadataKey), out _);
        if (!ecdsa.VerifyData(json, signature, HashAlgorithmName.SHA256, DSASignatureFormat.IeeeP1363FixedFieldConcatenation))
            throw new TrustException("Release metadata signature is invalid. The download was not produced by the CiciPDA release key.");
    }
}
