using System.Security.Cryptography;
using CiciPDA;

// Offline release tooling.
//   genkey <dir>                       create the ECDSA P-256 metadata-signing key pair (keep private.pk8 offline!)
//   sign <companion.json> <private.pk8> write companion.json.sig
//   pins <public.spki> <apk> <Pins.cs> [--dev]  emit the public pins compiled into the Windows app
if (args.Length < 2) { Console.Error.WriteLine("usage: genkey|sign|pins ..."); return 2; }
switch (args[0])
{
    case "genkey":
    {
        Directory.CreateDirectory(args[1]);
        using var k = ECDsa.Create(ECCurve.NamedCurves.nistP256);
        File.WriteAllText(Path.Combine(args[1], "private.pk8"), Convert.ToBase64String(k.ExportPkcs8PrivateKey()));
        File.WriteAllText(Path.Combine(args[1], "public.spki"), Convert.ToBase64String(k.ExportSubjectPublicKeyInfo()));
        Console.WriteLine("Keys written to " + args[1]);
        return 0;
    }
    case "sign":
    {
        using var k = ECDsa.Create();
        k.ImportPkcs8PrivateKey(Convert.FromBase64String(File.ReadAllText(args[2]).Trim()), out _);
        var json = File.ReadAllBytes(args[1]);
        File.WriteAllBytes(args[1] + ".sig", k.SignData(json, HashAlgorithmName.SHA256, DSASignatureFormat.IeeeP1363FixedFieldConcatenation));
        Console.WriteLine("Signed " + args[1]);
        return 0;
    }
    case "pins":
    {
        var pub = File.ReadAllText(args[1]).Trim();
        var certs = ApkSigning.SignerCertSha256(args[2]);
        bool dev = args.Contains("--dev");
        File.WriteAllText(args[3], $$"""
            // <auto-generated> by tools/ReleaseSigner. Contains PUBLIC pins only.
            namespace CiciPDA;
            static class Pins
            {
                public const bool IsDevelopment = {{(dev ? "true" : "false")}};
                public const string MetadataKey = "{{pub}}";
                public static readonly string[] SignerCerts = { {{string.Join(", ", certs.Select(c => "\"" + c + "\""))}} };
            }
            """);
        Console.WriteLine("Pins written: " + string.Join(",", certs));
        return 0;
    }
}
return 2;
